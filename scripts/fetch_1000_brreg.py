#!/usr/bin/env python3
"""Fetch real Norwegian company profiles from the Brreg Enhetsregisteret open API.

Writes:
  db/profiles_1000.json  - the profiles (default 1,050 records)
  db/init.sql            - SQL INSERTs appended inside an idempotent marked block

Financials (revenue_nok / ebitda_nok) are always null: Brreg's entity endpoint carries
no audited financials, so they are withheld rather than estimated.

delta_sync_hash = SHA-256 over canonical JSON (sorted keys, no whitespace, UTF-8, no
ASCII escaping) of the 7 registry fields below. Timestamp and source_url are excluded so
the hash is stable for unchanged registry data. frontend/src/lib/brregFallback.ts uses
the identical canonicalisation.
"""
import hashlib
import json
import sys
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "https://data.brreg.no/enhetsregisteret/api/enheter"
COUNT = 1050
BEGIN = "-- BEGIN brreg-profiles (generated by scripts/fetch_1000_brreg.py)"
END = "-- END brreg-profiles"


def get_json(url, retries=3):
    for attempt in range(retries):
        try:
            req = urllib.request.Request(url, headers={"Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.load(resp)
        except Exception as exc:  # noqa: BLE001
            if attempt == retries - 1:
                raise
            print(f"retry {attempt + 1} after error: {exc}", file=sys.stderr)
            time.sleep(2 * (attempt + 1))


def canonical(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def registry_payload(e):
    return {
        "organisasjonsnummer": e.get("organisasjonsnummer"),
        "navn": e.get("navn"),
        "organisasjonsform_kode": (e.get("organisasjonsform") or {}).get("kode"),
        "stiftelsesdato": e.get("stiftelsesdato"),
        "antallAnsatte": e.get("antallAnsatte"),
        "naeringskode1_beskrivelse": (e.get("naeringskode1") or {}).get("beskrivelse"),
        "forretningsadresse": e.get("forretningsadresse"),
    }


def build_record(e, fetched_at):
    payload = registry_payload(e)
    orgnr = payload["organisasjonsnummer"]
    return {
        **payload,
        "delta_sync_hash": hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest(),
        "source_url": f"{BASE}/{orgnr}",
        "fetched_at": fetched_at,
        "revenue_nok": None,
        "ebitda_nok": None,
        "financials_status": "withheld_no_proof",
    }


def fetch_entities(count):
    data = get_json(f"{BASE}?size={count}")
    entities = (data.get("_embedded") or {}).get("enheter", [])
    page = 1
    while len(entities) < count:  # top up if the API returned fewer than requested
        data = get_json(f"{BASE}?size={count}&page={page}")
        more = (data.get("_embedded") or {}).get("enheter", [])
        if not more:
            break
        entities += more
        page += 1
    return entities


def address_text(addr):
    if not addr:
        return None
    parts = [", ".join(addr.get("adresse") or []), " ".join(filter(None, [addr.get("postnummer"), addr.get("poststed")])), addr.get("land")]
    return ", ".join(p for p in parts if p) or None


def q(value):
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def sql_block(records):
    lines = [BEGIN]
    for i in range(0, len(records), 100):
        chunk = records[i:i + 100]
        rows = ",\n".join(
            f"({q(r['organisasjonsnummer'])}, {q(r['navn'])}, {q(address_text(r['forretningsadresse']))}, "
            f"{q(r['stiftelsesdato'])}, 'N/A', 'N/A', {q(r['delta_sync_hash'])}, {q(r['fetched_at'])})"
            for r in chunk
        )
        lines.append(
            "INSERT INTO compiled_companies (company_number, official_legal_name, registered_address, "
            "incorporation_date, financial_revenue, net_profit, delta_sync_hash, last_modified_timestamp)\nVALUES\n"
            + rows
            + "\nON CONFLICT (company_number) DO UPDATE SET official_legal_name = EXCLUDED.official_legal_name, "
            "registered_address = EXCLUDED.registered_address, incorporation_date = EXCLUDED.incorporation_date, "
            "financial_revenue = 'N/A', net_profit = 'N/A', delta_sync_hash = EXCLUDED.delta_sync_hash, "
            "last_modified_timestamp = EXCLUDED.last_modified_timestamp;"
        )
    for i in range(0, len(records), 100):
        chunk = records[i:i + 100]
        rows = ",\n".join(
            f"({q(r['organisasjonsnummer'])}, 'OFFICIAL_REGISTRY_ANCHOR', "
            + q(f"Verified Legal Name: {r['navn']} | OrgNr: {r['organisasjonsnummer']} | Address: {address_text(r['forretningsadresse']) or 'n/a'}")
            + f", {q(r['source_url'])}, {q(r['fetched_at'])}, "
            "'STEP 1: Brreg API record fetched -> STEP 2: registry fields canonicalised -> STEP 3: SHA-256 delta hash anchored. Revenue/EBITDA withheld (no proof).')"
            for r in chunk
        )
        lines.append(
            "INSERT INTO lineage_evidences (company_number, target_metric_key, extracted_text_snippet, "
            "source_url_link, crawl_timestamp, explanation_chain)\nVALUES\n" + rows + ";"
        )
    lines.append(END)
    return "\n".join(lines) + "\n"


def write_sql(path, block):
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if BEGIN in text and END in text:  # replace previous generated block -> idempotent
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1].lstrip("\n")
        text = head.rstrip("\n") + "\n\n" + block + ("\n" + tail if tail else "")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    path.write_text(text, encoding="utf-8")


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else COUNT
    fetched_at = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    entities = [e for e in fetch_entities(count) if e.get("organisasjonsnummer") and e.get("navn")][:count]
    if len(entities) < count:
        sys.exit(f"Only {len(entities)} usable records fetched (wanted {count}); not writing partial output.")
    records = [build_record(e, fetched_at) for e in entities]
    out = ROOT / "db" / "profiles_1000.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_sql(ROOT / "db" / "init.sql", sql_block(records))
    print(f"Wrote {len(records)} records to {out} and updated db/init.sql")


if __name__ == "__main__":
    main()
